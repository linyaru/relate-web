// Build-time transforms of the site's artifacts for the Worker (pure: the
// bundle script and the unit tests use them; no Node imports).
//
// - seedWithoutVectors / seedVectors: the served seed (/docs/graph.cypher)
//   split into the replay without the section vectors and the vectors as
//   `{id, v}` rows for VECTOR_LOAD_STATEMENT (ADR-0028). VECTOR_SEED_END and
//   seedWithoutVectors are copies of src/lib/docs/graph.ts's, which imports
//   modules this package does not install; src/hybrid.test.ts asserts the
//   copies give graph.ts's bytes.
// - factoryGlue: public/wasm/relate.js inside a function, so each call holds
//   its own wasm-bindgen state and validate_cypher gets a fresh WebAssembly
//   instance of the same compiled module per call (src/wasm.ts).

export const VECTOR_LOAD_STATEMENT = 'UNWIND $rows AS row MATCH (s:Section {id: row.id}) SET s.embedding = vector(row.v, 384, FLOAT32)';
export const VECTOR_SEED_END = `${VECTOR_LOAD_STATEMENT.replace('UNWIND $rows AS row', '] AS row')};`;

export function seedWithoutVectors(seed: string): string {
  const lines = seed.split('\n');
  const out: string[] = [];
  let removed = 0;
  for (let i = 0; i < lines.length; i++) {
    if (lines[i] !== 'UNWIND [') {
      out.push(lines[i]);
      continue;
    }
    let j = i + 1;
    while (j < lines.length && !lines[j].startsWith('] AS row ')) j++;
    if (j === lines.length) throw new Error(`seedWithoutVectors: the UNWIND statement at line ${i + 1} has no end`);
    if (lines[j] === VECTOR_SEED_END) {
      // seedScript() puts one blank line before the first vector statement.
      if (removed === 0 && out[out.length - 1] === '') out.pop();
      removed++;
    } else {
      out.push(...lines.slice(i, j + 1));
    }
    i = j;
  }
  return out.join('\n');
}

/** A single-quoted Cypher string literal as graph.ts cypherLiteral() writes it, unescaped. */
function cypherString(lit: string): string {
  return lit.slice(1, -1).replace(/\\(u[0-9a-f]{4}|.)/g, (_, c: string) =>
    c[0] === 'u' && c.length === 5 ? String.fromCharCode(parseInt(c.slice(1), 16)) : c === 'n' ? '\n' : c === 'r' ? '\r' : c === 't' ? '\t' : c,
  );
}

/** The section vectors the served seed sets, as `{id, v}` rows, from its vector statements. Throws on a row it cannot read. */
export function seedVectors(seed: string, dimension = 384): { id: string; v: number[] }[] {
  const lines = seed.split('\n');
  const rows: { id: string; v: number[] }[] = [];
  for (let i = 0; i < lines.length; i++) {
    if (lines[i] !== 'UNWIND [') continue;
    let j = i + 1;
    while (j < lines.length && !lines[j].startsWith('] AS row ')) j++;
    if (lines[j] === VECTOR_SEED_END) {
      for (const line of lines.slice(i + 1, j)) {
        const m = /^\{id: ('(?:[^'\\]|\\.)*'), v: \[([^\]]*)\]\},?$/.exec(line);
        if (!m) throw new Error(`a vector row is not {id, v}: ${line.slice(0, 80)}`);
        const v = JSON.parse(`[${m[2]}]`) as number[];
        if (v.length !== dimension) throw new Error(`the vector of ${m[1]} has ${v.length} values, not ${dimension}`);
        rows.push({ id: cypherString(m[1]), v });
      }
    }
    i = j;
  }
  return rows;
}

/** relate.js as an ES module exporting `createRelate(console)`. Throws when the glue's shape is not the one this expects. */
export function factoryGlue(src: string): string {
  const imp = /^import \{([^}]+)\} from '(\.\/snippets\/[^']+)';\n/m;
  const m = imp.exec(src);
  if (!m) throw new Error('no snippets import line; the glue changed shape, update factoryGlue in scripts/seed.ts');
  let body = src.replace(imp, '');
  const tail = 'export { initSync, __wbg_init as default };';
  if (!body.includes(tail)) throw new Error('no closing export line; update factoryGlue in scripts/seed.ts');
  body = body.replace(tail, '');
  if (!/^export class RelateDb /m.test(body) || !/^function initSync\(/m.test(body)) throw new Error('RelateDb or initSync not found; update factoryGlue in scripts/seed.ts');
  body = body.replace(/^export (class|function|const|let) /gm, '$1 ');
  if (/^\s*(export|import) /m.test(body)) throw new Error('an export or import is left after the transform; update factoryGlue in scripts/seed.ts');
  return [
    '// Generated by workers/docs-mcp/scripts/bundle.ts from public/wasm/relate.js: the same glue',
    '// inside a function, so each call holds its own instance state. `console` is the',
    "// caller's (validate_cypher passes a silent one: a panic's message never reaches the log).",
    `import {${m[1]}} from '${m[2]}';`,
    'export function createRelate(console) {',
    body,
    'return { initSync, RelateDb };',
    '}',
    '',
  ].join('\n');
}
