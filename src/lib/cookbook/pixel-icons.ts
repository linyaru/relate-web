/** The SVG path, width and height of a category's (or `down`'s) icon; unknown keys fall back to Agent memory. */
export function pixels(key: string): { d: string; w: number; h: number } {
  const rows = PX[key] ?? PX['Agent memory'];
  const d = rows.flatMap((row, y) => [...row].map((c, x) => (c === '#' ? `M${x} ${y}h1v1h-1z` : ''))).join('');
  return { d, w: rows[0].length, h: rows.length };
}
