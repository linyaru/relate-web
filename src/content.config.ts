// Content collections (DOCS-PLAN.md §5): the docs pages, the glossary and the
// capability catalog.
// The cookbook stays outside collections; its own parser owns
// src/content/cookbook (src/lib/cookbook/).

import { defineCollection } from 'astro:content';
import { glob } from 'astro/loaders';
import { z } from 'astro/zod';

import { DOCS_PATTERNS } from './lib/docs/content.ts';
import { DOC_TYPES, GENERATED_FIELDS, idFromPath, SECTION_IDS, STATUSES, SURFACES } from './lib/docs/model.ts';

const generated = Object.fromEntries(
  GENERATED_FIELDS.map((f) => [f, z.never({ error: `\`${f}\` is generated by the build; remove it from the frontmatter` }).optional()]),
);

/**
 * A docs page: src/content/docs/<section>/…/<name>.mdx, served at
 * /docs/<section>/…/<name>/ (an `index.mdx` serves its directory's URL).
 * `section` and `type` follow from the path; when a page states them they
 * must agree (src/lib/docs/site.ts checks). `verified`, `canonical_url` and
 * `last_updated` are generated. `status: planned` leaves the page out.
 */
const docs = defineCollection({
  loader: glob({ pattern: DOCS_PATTERNS, base: './src/content/docs', generateId: ({ entry }) => idFromPath(entry) }),
  schema: z
    .object({
      title: z.string().min(1),
      /** The sidebar label, when shorter than the title. */
      label: z.string().min(1).optional(),
      /** Required unless `status: planned` (a stub that declares a forward link). */
      description: z.string().min(1).optional(),
      section: z.enum(SECTION_IDS).optional(),
      type: z.enum(DOC_TYPES).optional(),
      /** Sidebar order within the page's group (lower first; ties sort by title). */
      order: z.number().int().default(100),
      surfaces: z.array(z.enum(SURFACES)).default([]),
      status: z.enum(STATUSES).default('stable'),
      since: z.string().regex(/^\d+\.\d+(\.\d+)?$/, 'a version like 0.17 or 0.17.0').optional(),
      /** Page ids to read first (`get-started/install`). */
      prerequisites: z.array(z.string()).default([]),
      /** Page ids (with an optional #anchor) or `cookbook/<slug>`. */
      related: z.array(z.string()).default([]),
      ...generated,
    })
    .strict()
    .superRefine((d, ctx) => {
      if (d.status !== 'planned' && !d.description) {
        ctx.addIssue({ code: 'custom', path: ['description'], message: '`description` is required unless `status: planned`' });
      }
    }),
});

/** A glossary term: src/content/docs/_glossary/<id>.mdx (DOCS-PLAN.md §4.11). */
const glossary = defineCollection({
  loader: glob({ pattern: '*.mdx', base: './src/content/docs/_glossary' }),
  schema: z
    .object({
      id: z.string().regex(/^[a-z0-9-]+$/),
      term: z.string().min(1),
      short: z.string().min(1).max(160),
      aliases: z.array(z.string()).default([]),
      context: z.enum(['cypher', 'storage', 'cli', 'agents', 'surfaces', 'engine']),
      see: z.string().optional(),
      related: z.array(z.string()).default([]),
    })
    .strict(),
});

/**
 * A capability: src/content/docs/_capabilities/<id>.mdx (DOCS-PLAN.md §3.8).
 * The body is two to four paragraphs. src/lib/docs/capabilities.ts reads the
 * files from disk and checks what this schema cannot: the id is the slug of
 * the title, the cited pages, recipes and verify run exist, intents are
 * unique across the catalog and carry no injection phrasing.
 */
const capabilities = defineCollection({
  loader: glob({ pattern: '*.mdx', base: './src/content/docs/_capabilities' }),
  schema: z
    .object({
      id: z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/),
      /** The H2 on concepts/problems-relate-solves; its slug is `id`. */
      title: z.string().min(1),
      order: z.number().int(),
      /** The problem in the reader's words. */
      problem: z.string().min(1).max(200),
      /** The capability in the product's words. */
      capability: z.string().min(1).max(200),
      intents: z.array(z.string().min(1)).min(4).max(8),
      surfaces: z.array(z.enum(SURFACES)).min(1),
      /** Page ids, with an optional #anchor. */
      guides: z.array(z.string()).default([]),
      /** Cookbook slugs. */
      recipes: z.array(z.string()).default([]),
      /** Page ids, with an optional #anchor. */
      reference: z.array(z.string()).default([]),
      /** The recommended data model: a mermaid flowchart whose nodes are all circles, or null. */
      schema: z.string().min(1).nullable(),
      /** `<recipe slug>#<cell id>`, `<page id>#<cell id>` or `<page id>#step-<n>`; null when no recorded run exercises it yet. */
      verify: z.string().regex(/^[^#\s]+#[A-Za-z0-9_-]+$/).nullable(),
    })
    .strict(),
});

export const collections = { docs, glossary, capabilities };
